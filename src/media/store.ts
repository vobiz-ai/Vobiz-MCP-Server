/**
 * Durable audio library storage. Neither store ever sees an auth token: AudioMeta has no such field and the
 * stores copy only AudioMeta fields.
 *
 *   LocalDiskMediaStore  dev, tests and single-host deployments: `${dir}/accounts/<hash>/<id>.wav|.json`
 *   GcsMediaStore        hosted (Cloud Run): `${prefix}accounts/<hash>/<id>.wav|.json` in a private bucket
 *
 * <hash> is the first 16 hex chars of sha256(authId), so the Auth ID itself never appears in a path.
 * The JSON sidecar is the source of truth for metadata; list() reads only sidecars.
 * The daily upload counter lives apart from the library, at `counters/<hash>.json`, so deleting files never resets it.
 */
import { createReadStream } from "node:fs";
import { mkdir, readFile, readdir, rename, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { accountHash } from "../reminders/store.js";
import type { AudioMeta, MediaStore } from "./types.js";

/** Ids are generated by the service (`a_` + base64url); anything else never reaches the filesystem or bucket. */
const ID_RE = /^[A-Za-z0-9_-]{1,64}$/;
export function isValidAudioId(id: string): boolean {
  return typeof id === "string" && ID_RE.test(id);
}

const SOURCES: AudioMeta["source"][] = ["upload", "url", "phone"];

/** Copies only AudioMeta fields; returns undefined for anything malformed. */
export function cleanMeta(m: unknown): AudioMeta | undefined {
  if (!m || typeof m !== "object") return undefined;
  const r = m as Record<string, unknown>;
  if (typeof r.id !== "string" || !isValidAudioId(r.id) || typeof r.authId !== "string" || typeof r.name !== "string") return undefined;
  if (typeof r.durationSec !== "number" || typeof r.bytes !== "number" || typeof r.createdAt !== "string") return undefined;
  const source = SOURCES.includes(r.source as AudioMeta["source"]) ? (r.source as AudioMeta["source"]) : "upload";
  const out: AudioMeta = {
    id: r.id,
    authId: r.authId,
    name: r.name,
    durationSec: r.durationSec,
    bytes: r.bytes,
    contentType: "audio/wav",
    source,
    createdAt: r.createdAt,
  };
  if (typeof r.origin === "string" && r.origin) out.origin = r.origin;
  return out;
}

const DAY_RE = /^\d{4}-\d{2}-\d{2}$/;

/** Next value of a {day, count} counter: +1 on the same day, 1 on a new day. */
function nextCount(prev: unknown, day: string): number {
  const p = prev && typeof prev === "object" ? (prev as { day?: unknown; count?: unknown }) : {};
  const n = Number(p.count);
  return p.day === day && Number.isInteger(n) && n >= 0 ? n + 1 : 1;
}

/** Relative path of an account's daily counter. */
export function counterPath(authId: string): string {
  return `counters/${accountHash(authId)}.json`;
}

const newestFirst = (a: AudioMeta, b: AudioMeta) => (a.createdAt < b.createdAt ? 1 : a.createdAt > b.createdAt ? -1 : 0);

/** Relative object path of an account's library folder. */
export function accountDir(authId: string): string {
  return `accounts/${accountHash(authId)}`;
}

// ── Local disk ────────────────────────────────────────────────────

export const DEFAULT_MEDIA_DIR = join(tmpdir(), "vobiz-mcp-media");

export class LocalDiskMediaStore implements MediaStore {
  constructor(readonly dir: string = DEFAULT_MEDIA_DIR) {}

  private folder(authId: string): string {
    return join(this.dir, ...accountDir(authId).split("/"));
  }
  private paths(authId: string, id: string) {
    const f = this.folder(authId);
    return { wav: join(f, `${id}.wav`), json: join(f, `${id}.json`) };
  }

  async put(meta: AudioMeta, wav: Buffer): Promise<void> {
    const m = cleanMeta(meta);
    if (!m) throw new Error("invalid audio metadata");
    const p = this.paths(m.authId, m.id);
    await mkdir(this.folder(m.authId), { recursive: true, mode: 0o700 });
    // Write the file first and the sidecar last (atomically), so list() never shows an entry without audio.
    await writeFile(`${p.wav}.tmp`, wav, { mode: 0o600 });
    await rename(`${p.wav}.tmp`, p.wav);
    await writeFile(`${p.json}.tmp`, JSON.stringify(m), { mode: 0o600 });
    await rename(`${p.json}.tmp`, p.json);
  }

  async getMeta(authId: string, id: string): Promise<AudioMeta | undefined> {
    if (!isValidAudioId(id)) return undefined;
    try {
      const m = cleanMeta(JSON.parse(await readFile(this.paths(authId, id).json, "utf8")));
      return m && m.authId === authId && m.id === id ? m : undefined;
    } catch {
      return undefined;
    }
  }

  async open(authId: string, id: string): Promise<NodeJS.ReadableStream | undefined> {
    if (!(await this.getMeta(authId, id))) return undefined;
    const wav = this.paths(authId, id).wav;
    try {
      await stat(wav);
    } catch {
      return undefined;
    }
    return createReadStream(wav);
  }

  async list(authId: string): Promise<AudioMeta[]> {
    let names: string[];
    try {
      names = await readdir(this.folder(authId));
    } catch {
      return [];
    }
    const out: AudioMeta[] = [];
    for (const n of names) {
      if (!n.endsWith(".json")) continue;
      const m = await this.getMeta(authId, n.slice(0, -5));
      if (m) out.push(m);
    }
    return out.sort(newestFirst);
  }

  async delete(authId: string, id: string): Promise<boolean> {
    if (!(await this.getMeta(authId, id))) return false;
    const p = this.paths(authId, id);
    await rm(p.json, { force: true });
    await rm(p.wav, { force: true });
    return true;
  }

  async count(authId: string): Promise<number> {
    try {
      return (await readdir(this.folder(authId))).filter((n) => n.endsWith(".json") && isValidAudioId(n.slice(0, -5))).length;
    } catch {
      return 0;
    }
  }

  /** Per-process queue per counter file, so concurrent increments in this process never lose an update. */
  private readonly counterLocks = new Map<string, Promise<unknown>>();

  incrementDaily(authId: string, day: string): Promise<number> {
    if (!DAY_RE.test(day)) return Promise.reject(new Error("invalid day"));
    const file = join(this.dir, ...counterPath(authId).split("/"));
    const prev = this.counterLocks.get(file) ?? Promise.resolve();
    const run = prev.catch(() => undefined).then(async () => {
      let cur: unknown;
      try {
        cur = JSON.parse(await readFile(file, "utf8"));
      } catch {
        cur = undefined;
      }
      const count = nextCount(cur, day);
      await mkdir(join(this.dir, "counters"), { recursive: true, mode: 0o700 });
      const tmp = `${file}.${process.pid}.${Date.now()}.tmp`;
      await writeFile(tmp, JSON.stringify({ day, count }), { mode: 0o600 });
      await rename(tmp, file); // atomic replace: a reader sees the old or the new counter, never a torn one
      return count;
    });
    this.counterLocks.set(file, run);
    void run.finally(() => {
      if (this.counterLocks.get(file) === run) this.counterLocks.delete(file);
    }).catch(() => undefined);
    return run;
  }
}

// ── Google Cloud Storage ─────────────────────────────────────────
// Minimal structural view of the Storage client, so the module is only imported when this store is used
// (and so tests can pass a fake).

export interface GcsFileLike {
  name: string;
  save(
    data: Buffer | string,
    o?: { contentType?: string; resumable?: boolean; metadata?: Record<string, unknown>; preconditionOpts?: { ifGenerationMatch?: number | string } },
  ): Promise<unknown>;
  /** Object metadata incl. `generation` and custom `metadata`; rejects with code 404 when missing. */
  getMetadata?(): Promise<[{ generation?: number | string; metadata?: Record<string, unknown> }, ...unknown[]]>;
  download(): Promise<[Buffer]>;
  exists(): Promise<[boolean]>;
  delete(o?: { ignoreNotFound?: boolean }): Promise<unknown>;
  createReadStream(): NodeJS.ReadableStream;
}
export interface GcsBucketLike {
  file(name: string): GcsFileLike;
  getFiles(o: { prefix: string; matchGlob?: string; autoPaginate?: boolean }): Promise<[GcsFileLike[], ...unknown[]]>;
}

export interface GcsMediaStoreOptions {
  bucket: string;
  /** Object name prefix, e.g. "media/". Default none. */
  prefix?: string;
  /** Injected bucket (tests). Otherwise @google-cloud/storage is imported on first use. */
  client?: GcsBucketLike;
}

/** Hard cap on sidecars read per list() (maxPerAccount is far below it). */
const LIST_SCAN = 1000;
/** Attempts for a contended counter update (412 precondition failures), with jittered backoff. */
const COUNTER_ATTEMPTS = 8;

const errCode = (e: unknown) => Number((e as { code?: unknown })?.code ?? (e as { response?: { status?: unknown } })?.response?.status);

export class GcsMediaStore implements MediaStore {
  private readonly prefix: string;
  private bucketPromise?: Promise<GcsBucketLike>;

  constructor(private readonly o: GcsMediaStoreOptions) {
    if (!o.bucket) throw new Error("GcsMediaStore needs a bucket");
    this.prefix = o.prefix ? o.prefix.replace(/^\/+/, "").replace(/\/*$/, "/") : "";
    if (o.client) this.bucketPromise = Promise.resolve(o.client);
  }

  private bucket(): Promise<GcsBucketLike> {
    this.bucketPromise ??= import("@google-cloud/storage").then(
      ({ Storage }) => new Storage().bucket(this.o.bucket) as unknown as GcsBucketLike,
    );
    return this.bucketPromise;
  }

  private folder(authId: string): string {
    return `${this.prefix}${accountDir(authId)}/`;
  }
  objectName(authId: string, id: string, ext: "wav" | "json"): string {
    return `${this.folder(authId)}${id}.${ext}`;
  }

  async put(meta: AudioMeta, wav: Buffer): Promise<void> {
    const m = cleanMeta(meta);
    if (!m) throw new Error("invalid audio metadata");
    const b = await this.bucket();
    // Custom metadata on the audio object is informational only (no Auth ID, no name); the sidecar is the source of truth.
    await b.file(this.objectName(m.authId, m.id, "wav")).save(wav, {
      contentType: "audio/wav",
      resumable: false,
      metadata: { cacheControl: "private, no-store", metadata: { id: m.id, durationSec: String(m.durationSec), source: m.source } },
    });
    await b.file(this.objectName(m.authId, m.id, "json")).save(JSON.stringify(m), {
      contentType: "application/json",
      resumable: false,
      metadata: { cacheControl: "private, no-store" },
    });
  }

  private async readSidecar(f: GcsFileLike, authId: string): Promise<AudioMeta | undefined> {
    try {
      const [buf] = await f.download();
      const m = cleanMeta(JSON.parse(buf.toString("utf8")));
      return m && m.authId === authId ? m : undefined;
    } catch {
      return undefined;
    }
  }

  async getMeta(authId: string, id: string): Promise<AudioMeta | undefined> {
    if (!isValidAudioId(id)) return undefined;
    const m = await this.readSidecar((await this.bucket()).file(this.objectName(authId, id, "json")), authId);
    return m && m.id === id ? m : undefined;
  }

  async open(authId: string, id: string): Promise<NodeJS.ReadableStream | undefined> {
    if (!(await this.getMeta(authId, id))) return undefined;
    const f = (await this.bucket()).file(this.objectName(authId, id, "wav"));
    const [exists] = await f.exists();
    return exists ? f.createReadStream() : undefined;
  }

  async list(authId: string): Promise<AudioMeta[]> {
    const [files] = await (await this.bucket()).getFiles({ prefix: this.folder(authId), matchGlob: "**.json", autoPaginate: true });
    const sidecars = files.filter((f) => f.name.endsWith(".json")).slice(0, LIST_SCAN);
    const metas = await Promise.all(sidecars.map((f) => this.readSidecar(f, authId)));
    return metas.filter((m): m is AudioMeta => !!m).sort(newestFirst);
  }

  async count(authId: string): Promise<number> {
    const [files] = await (await this.bucket()).getFiles({ prefix: this.folder(authId), matchGlob: "**.json", autoPaginate: true });
    return files.filter((f) => f.name.endsWith(".json") && isValidAudioId(f.name.slice(this.folder(authId).length, -5))).length;
  }

  /**
   * Compare-and-swap on one small object per account. The count is read from object metadata together with its
   * generation (one call), and written back with ifGenerationMatch (0 = must not exist yet); a concurrent writer
   * makes the write fail with 412 and this retries, so replicas never lose an increment.
   */
  async incrementDaily(authId: string, day: string): Promise<number> {
    if (!DAY_RE.test(day)) throw new Error("invalid day");
    const f = (await this.bucket()).file(`${this.prefix}${counterPath(authId)}`);
    if (!f.getMetadata) throw new Error("GCS client without getMetadata");
    for (let attempt = 1; ; attempt++) {
      let generation: number | string = 0;
      let prev: unknown;
      try {
        const [md] = await f.getMetadata();
        generation = md.generation ?? 0;
        prev = md.metadata;
      } catch (e) {
        if (errCode(e) !== 404) throw e;
      }
      const count = nextCount(prev, day);
      try {
        await f.save(JSON.stringify({ day, count }), {
          contentType: "application/json",
          resumable: false,
          metadata: { cacheControl: "private, no-store", metadata: { day, count: String(count) } },
          preconditionOpts: { ifGenerationMatch: generation },
        });
        return count;
      } catch (e) {
        const code = errCode(e);
        if ((code !== 412 && code !== 409) || attempt >= COUNTER_ATTEMPTS) throw e;
        await new Promise((r) => setTimeout(r, Math.random() * 25 * attempt));
      }
    }
  }

  async delete(authId: string, id: string): Promise<boolean> {
    if (!(await this.getMeta(authId, id))) return false;
    const b = await this.bucket();
    await b.file(this.objectName(authId, id, "json")).delete({ ignoreNotFound: true });
    await b.file(this.objectName(authId, id, "wav")).delete({ ignoreNotFound: true });
    return true;
  }
}
